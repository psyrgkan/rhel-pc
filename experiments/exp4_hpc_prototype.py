"""Experiment 4 — Hamiltonian Predictive Coding prototype (proposal demo).

Three claims, each checked numerically (see docs/pc_proposal.md):

(1) Exactness: RHEL through the HPC inference dynamics equals BPTT
    (Theorem 3.2 applies because the PC Hamiltonian is separable).
(2) Locality: the RHEL weight update for the PC Hamiltonian *is* the PC
    Hebbian rule -- a contrast of (prediction error x presynaptic activity)
    outer products along the two echo trajectories. We verify the
    hand-written Hebbian formula matches the generic autodiff estimator.
(3) Learning: an HPC classifier trains on the delayed-cue task equally
    well with RHEL and with BPTT.

Run:  python experiments/exp4_hpc_prototype.py
"""

import json
import os
import sys
import time

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

import jax

jax.config.update("jax_enable_x64", True)

import jax.numpy as jnp
import jax.random as jr
import matplotlib
import numpy as np
import optax

matplotlib.use("Agg")
import matplotlib.pyplot as plt

from rhel.data import make_splits
from rhel.hamiltonian import hru_scan
from rhel.models import cross_entropy_loss
from rhel.predictive_coding import HPCClassifier, init_hpc, pc_errors

LEVELS, WIDTH, DELTA, ALPHA = 3, 16, 0.1, 0.3
SEQ_LEN, CHANNELS, CLASSES = 120, 4, 4
# Persistent cue: a non-dissipative system cannot forget injected noise
# (App. A.4.4), so the discriminative signal must be present at all steps.


def _flat(tree):
    return jnp.concatenate([jnp.ravel(x) for x in jax.tree.leaves(tree)])


def _cos(a, b):
    a, b = _flat(a), _flat(b)
    return float(jnp.dot(a, b) / (jnp.linalg.norm(a) * jnp.linalg.norm(b)))


# ---- (1) gradient exactness ------------------------------------------------


def check_exactness(key):
    params = init_hpc(key, LEVELS, WIDTH, CHANNELS, CLASSES)
    params = jax.tree.map(lambda x: x.astype(jnp.float64), params)
    u = jr.normal(jr.fold_in(key, 1), (SEQ_LEN, CHANNELS), dtype=jnp.float64)
    y = jax.nn.one_hot(0, CLASSES, dtype=jnp.float64)
    grads = {}
    for alg in ("BPTT", "RHEL"):
        m = HPCClassifier(LEVELS, WIDTH, DELTA, ALPHA, alg, epsilon=1e-6)
        grads[alg] = jax.grad(
            lambda p: cross_entropy_loss(m, p, u[None], y[None])
        )(params)
    cos = _cos(grads["BPTT"], grads["RHEL"])
    ratio = float(jnp.linalg.norm(_flat(grads["RHEL"])) /
                  jnp.linalg.norm(_flat(grads["BPTT"])))
    print(f"(1) exactness: cos(RHEL, BPTT) = {cos:.12f}, norm ratio = {ratio:.8f}")
    return {"cosine": cos, "norm_ratio": ratio}, grads["RHEL"], params, u, y


# ---- (2) locality: RHEL update == contrastive Hebbian PC rule ---------------


def hebbian_updates(model, params, u_seq, g_seq, eps):
    """Hand-written PC rule: Delta W_l = delta/(2 eps) [e_l f(z_{l+1})^T]_+^-.

    Echo trajectories are generated by the same forward dynamics (hru_scan);
    the update uses only locally available quantities at each connection:
    the prediction error at its output and the presynaptic activity at its
    input, evaluated at the leapfrog half-step positions.
    """
    spec = model.spec
    p = params["pc"]
    z0 = jnp.zeros(LEVELS * WIDTH, dtype=u_seq.dtype)
    (phiK, piK), _ = hru_scan(spec, p, z0, z0, u_seq)

    g_rev = g_seq[::-1]
    n0, n_seq = g_rev[0], jnp.concatenate([g_rev[1:], jnp.zeros_like(g_rev[:1])])
    u_rev = u_seq[::-1]

    def echo_halves(sign):
        e = sign * eps
        _, traj = hru_scan(spec, p, phiK, -piK + e * n0, u_rev, n_seq, e)
        return traj[2]  # phi_{k+1/3}: positions at the half step

    def hebb(phi13s):
        def per_step(phi13, u):
            errs, z = pc_errors(phi13, u, p, LEVELS, WIDTH)
            return [jnp.outer(errs[l], jnp.tanh(z[l])) for l in range(LEVELS)]
        terms = jax.vmap(per_step)(phi13s, u_rev)
        return [jnp.sum(t, axis=0) for t in terms]

    h_p, h_m = hebb(echo_halves(+1.0)), hebb(echo_halves(-1.0))
    return [DELTA / (2 * eps) * (a - b) for a, b in zip(h_p, h_m)]


def check_locality(model_rhel, grads_rhel, params, u, y):
    # upstream gradient of the loss w.r.t. the position trajectory, through
    # the same feedforward readout head used in the model (AD-differentiated)
    def head_loss(phis_flat):
        feats = jnp.tanh(phis_flat @ params["read_w"].T + params["read_b"])
        pooled = jnp.mean(feats, axis=0)
        logits = pooled @ params["dec_w"].T + params["dec_b"]
        return -jnp.sum(y * jax.nn.log_softmax(logits))

    phis = model_rhel.hru_apply(params["pc"], u, 0.0)
    g_seq = jax.grad(head_loss)(phis.reshape(SEQ_LEN, -1))
    dW_hebb = hebbian_updates(model_rhel, params, u, g_seq, eps=1e-6)
    # the contrastive Hebbian expression is the gradient estimate dL/dW
    # itself (Theorem 3.2); the descent update is its negation
    metrics = {}
    for l in range(LEVELS):
        gen = grads_rhel["pc"]["W"][l]
        diff = float(jnp.max(jnp.abs(dW_hebb[l] - gen)) /
                     (jnp.max(jnp.abs(gen)) + 1e-30))
        metrics[f"W{l}_max_rel_diff"] = diff
        print(f"(2) locality: Delta W_{l} Hebbian vs generic-RHEL "
              f"max rel diff = {diff:.2e}")
    return metrics


# ---- (3) training -----------------------------------------------------------


def train(alg, seed, data, steps=800, batch=32, lr=2e-3):
    (xtr, ytr), (xva, yva), (xte, yte) = data
    # gamma=1e2 keeps the float32 RHEL/BPTT gradient cosine at 1.0 for HPC
    # (the PC loss magnitudes make 1e4 over-scale; grid-searched, see report)
    eps, gamma = (0.1, 1e2) if alg == "RHEL" else (0.0, 1.0)
    model = HPCClassifier(LEVELS, WIDTH, DELTA, ALPHA, alg, epsilon=eps)
    params = init_hpc(jr.PRNGKey(seed), LEVELS, WIDTH, CHANNELS, CLASSES)
    params = jax.tree.map(lambda x: x.astype(jnp.float32), params)
    opt = optax.adam(lr)
    opt_state = opt.init(params)

    @jax.jit
    def step(params, opt_state, xb, yb):
        loss, grads = jax.value_and_grad(
            lambda p: cross_entropy_loss(model, p, xb, yb, grad_scaler=gamma)
        )(params)
        grads = jax.tree.map(lambda g: g / gamma, grads)
        updates, opt_state = opt.update(grads, opt_state)
        return optax.apply_updates(params, updates), opt_state, loss / gamma

    def acc(x, y):
        logits = jax.vmap(lambda u: model(params, u))(jnp.asarray(x[:300]))
        return float(jnp.mean(jnp.argmax(logits, -1) == jnp.argmax(jnp.asarray(y[:300]), -1)))

    rng = np.random.default_rng(seed)
    curve = []
    for s in range(steps):
        idx = rng.integers(0, len(xtr), batch)
        params, opt_state, loss = step(params, opt_state,
                                       jnp.asarray(xtr[idx]), jnp.asarray(ytr[idx]))
        if (s + 1) % 100 == 0:
            curve.append({"step": s + 1, "val_acc": acc(xva, yva)})
            print(f"  [HPC/{alg}/seed{seed}] step {s+1} val {curve[-1]['val_acc']:.3f}")
    return {"curve": curve, "test_acc": acc(xte, yte)}


def main():
    key = jr.PRNGKey(7)
    exact, grads_rhel, params, u, y = check_exactness(key)
    model_rhel = HPCClassifier(LEVELS, WIDTH, DELTA, ALPHA, "RHEL", epsilon=1e-6)
    local = check_locality(model_rhel, grads_rhel, params, u, y)

    data = make_splits(n_train=1500, n_val=300, n_test=300,
                       seq_len=SEQ_LEN, cue_len=SEQ_LEN, noise=1.0,
                       channels=CHANNELS, n_classes=CLASSES)
    training = {}
    for alg in ("BPTT", "RHEL"):
        runs = [train(alg, seed, data) for seed in (0, 1)]
        training[alg] = {
            "runs": runs,
            "test_mean": float(np.mean([r["test_acc"] for r in runs])),
            "test_std": float(np.std([r["test_acc"] for r in runs])),
        }
        print(f"== HPC {alg}: test acc {training[alg]['test_mean']*100:.1f} "
              f"+/- {training[alg]['test_std']*100:.1f} %")

    fig, ax = plt.subplots(figsize=(6, 4))
    for alg, color in (("BPTT", "tab:blue"), ("RHEL", "tab:red")):
        vals = np.array([[p["val_acc"] for p in r["curve"]] for r in training[alg]["runs"]])
        steps = [p["step"] for p in training[alg]["runs"][0]["curve"]]
        ax.plot(steps, vals.mean(0), color=color,
                label=f"{alg} (test {training[alg]['test_mean']*100:.1f}%)")
        ax.fill_between(steps, vals.min(0), vals.max(0), color=color, alpha=0.2)
    ax.axhline(1.0 / CLASSES, color="gray", ls=":", lw=1)
    ax.set_xlabel("training step"); ax.set_ylabel("validation accuracy")
    ax.set_title("Hamiltonian Predictive Coding trained by RHEL vs BPTT")
    ax.grid(True, ls="--", alpha=0.5); ax.legend()
    fig.tight_layout()
    os.makedirs("figures", exist_ok=True)
    fig.savefig("figures/exp4_hpc_prototype.png", dpi=160)

    os.makedirs("results", exist_ok=True)
    with open("results/exp4_hpc.json", "w") as f:
        json.dump({"exactness": exact, "locality": local, "training": training},
                  f, indent=2)
    print("saved figures/exp4_hpc_prototype.png")


if __name__ == "__main__":
    main()
