"""Hamiltonian Predictive Coding (HPC): applying RHEL to a PC network.

A classical predictive coding (PC) network (Rao & Ballard 1999; Whittington
& Bogacz 2017) is a hierarchy of value units z^(1..L) with top-down
predictions: level l+1 predicts level l through W^(l) f(z^(l+1)). Its free
energy, with the input u clamped at the bottom, is

    F(z; theta, u) = 1/2 ||u - W0 f(z1)||^2
                   + sum_{l=1}^{L-1} 1/2 ||z_l - W_l f(z_{l+1})||^2
                   + alpha/2 ||z||^2                                   (leak)

Standard PC runs *dissipative* inference z' = -dF/dz to equilibrium and
then applies the local Hebbian update dW ~ e_l f(z_{l+1})^T at that
equilibrium.

Here, instead, the value units are given momenta and follow *conservative*
second-order dynamics generated by the separable Hamiltonian

    H[Phi, theta, u] = 1/2 ||pi||^2 + F(phi; theta, u),

i.e. the whole PC hierarchy becomes one Hamiltonian Recurrent Unit
(Def. A.3 of the RHEL paper) driven at its sensory layer by a time-varying
input u_k. Inference is the leapfrog forward pass; learning is RHEL: flip
the momenta, replay the inputs backward with +/- eps nudges, and update

    Delta W_l = -1/(2 eps) [ grad_{W_l} F(echo+) - grad_{W_l} F(echo-) ]
              = +delta/(2 eps) [ e_l^+ f(z_{l+1}^+)^T - e_l^- f(z_{l+1}^-)^T ],

which is exactly the PC Hebbian rule, applied contrastively along the two
echo trajectories instead of at an equilibrium -- local in space, forward
in time, and (Theorem 3.2) equal to BPTT through the inference dynamics in
the limit eps -> 0.

See docs/pc_proposal.md for the full discussion.
"""

import jax
import jax.numpy as jnp
import jax.random as jr

from .hamiltonian import HamiltonianSpec, make_hru


def pc_errors(phi, u, p, levels, width):
    """Prediction errors e_0..e_{L-1} of the PC hierarchy."""
    z = phi.reshape(levels, width)
    errs = [u - p["W"][0] @ jnp.tanh(z[0])]
    for l in range(1, levels):
        errs.append(z[l - 1] - p["W"][l] @ jnp.tanh(z[l]))
    return errs, z


def make_hpc_spec(levels, width, delta, alpha):
    """Hamiltonian of the PC network, time step folded in (App. A.4.6)."""

    def kinetic(pi, p):
        return delta * 0.5 * jnp.sum(pi**2)

    def potential(phi, u, p):
        errs, z = pc_errors(phi, u, p, levels, width)
        f_err = sum(0.5 * jnp.sum(e**2) for e in errs)
        return delta * (f_err + 0.5 * alpha * jnp.sum(phi**2))

    return HamiltonianSpec(kinetic=kinetic, potential=potential)


def init_hpc(key, levels, width, data_dim, label_dim, feat_dim=32):
    ks = jr.split(key, levels + 3)
    Ws = [jr.uniform(ks[0], (data_dim, width), minval=-1, maxval=1) / jnp.sqrt(width)]
    Ws += [jr.uniform(k, (width, width), minval=-1, maxval=1) / jnp.sqrt(width)
           for k in ks[1:levels]]
    return {
        "pc": {"W": Ws},
        # readout head (AD-differentiated, chained with RHEL via Remark 8):
        # per-step linear map of all latents -> tanh -> mean-pool -> decode
        "read_w": jr.uniform(ks[-2], (feat_dim, levels * width), minval=-1, maxval=1) / jnp.sqrt(levels * width),
        "read_b": jnp.zeros((feat_dim,)),
        "dec_w": jr.uniform(ks[-1], (label_dim, feat_dim), minval=-1, maxval=1) / jnp.sqrt(feat_dim),
        "dec_b": jnp.zeros((label_dim,)),
    }


class HPCClassifier:
    """PC hierarchy as a single HRU + a small learned readout head.

    The recurrent credit assignment (the hard part) flows through RHEL/BPTT
    in the HRU; the readout head is plain feedforward differentiated by AD,
    exactly the RHEL-AD chaining the paper prescribes (Remark 8).
    """

    def __init__(self, levels, width, delta=0.1, alpha=0.1,
                 learning_algorithm="BPTT", epsilon=0.0):
        self.levels, self.width = levels, width
        self.epsilon = epsilon
        self.spec = make_hpc_spec(levels, width, delta, alpha)
        self.hru_apply = make_hru(self.spec, levels * width, learning_algorithm)

    def latents(self, params, u_seq):
        phis = self.hru_apply(params["pc"], u_seq, self.epsilon)  # (K, L*width)
        return phis.reshape(u_seq.shape[0], self.levels, self.width)

    def __call__(self, params, u_seq):
        phis = self.hru_apply(params["pc"], u_seq, self.epsilon)  # (K, L*width)
        feats = jnp.tanh(phis @ params["read_w"].T + params["read_b"])  # (K, feat)
        pooled = jnp.mean(feats, axis=0)
        return pooled @ params["dec_w"].T + params["dec_b"]
